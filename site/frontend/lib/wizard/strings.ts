// Localized strings for the config builder, per locale. Every field shows a
// human label (wizardLabels) with the raw YAML key beside it — the key is what
// you write in the file and what the docs reference verbatim, the label says
// what the field does. Field help is localized in wizardHelp; EN help is not
// duplicated here: it falls back to the overlay's `description` (see helpText
// in ConfigBuilder).

import type { Locale } from "@/lib/i18n";

export type SectionId =
  | "telemetry"
  | "networks"
  | "detection"
  | "mitigation"
  | "bans"
  | "notify"
  | "api";

export type WizardValidation = {
  required: string;
  enum: string; // "{allowed}" placeholder
  identifier: string; // regex-pattern failure (env/db/group names)
  notNumber: string;
  min: string; // "{min}" placeholder
  max: string; // "{max}" placeholder
  formats: Record<string, string>; // keyed by overlay `format`: ipv4/ipv6/ip/cidr/hostport/community/url
};

export type WizardChrome = {
  title: string;
  intro: string;
  privacy: string;
  advanced: string;
  output: string;
  copy: string;
  copied: string;
  download: string;
  checkHint: string;
  docsCta: string;
  accepts: string; // engine-accepts strip label
  liveWarning: string;
  addItem: string;
  addNeighbor: string;
  nav: string; // aria-label of the section rail
  modeWatch: string; // watch-only pill label
  modeLive: string; // live pill label
  modeWatchDesc: string;
  fieldErrors: string; // "{n}" placeholder
  engineChecking: string;
  engineOff: string;
  engineSummary: string;
  yamlJump: string; // collapsed-dock toggle label (opens the bottom YAML dock)
  minutes: string; // "{v}" placeholder — seconds-field gloss
  hours: string; // "{v}" placeholder
  sections: Record<SectionId, string>;
  subheads: {
    method: string;
    bgp: string;
    perProtocol: string;
    telegram: string;
    updates: string;
    baseline: string;
    carpet: string;
    samples: string;
    flowspec: string;
    escalation: string;
    scrubbing: string;
    dataplane: string;
    email: string;
    exec: string;
    storage: string;
    geoip: string;
  };
  advHints: Partial<Record<SectionId, string>>;
  // threshold-matrix chrome: row labels + the OR-semantics hint
  thr: {
    total: string;
    tcp: string;
    tcpSyn: string;
    udp: string;
    icmp: string;
    frag: string;
    flows: string;
    hint: string;
    perProto: string;
  };
  presets: {
    edge: { name: string; desc: string };
    single: { name: string; desc: string };
    carrier: { name: string; desc: string };
    confirm: string;
  };
  search: { placeholder: string; empty: string };
  modifiedChip: string; // "{n}" placeholder
  emptyList: string; // shown where a list has no entries yet
  presetLabel: string; // preset menu trigger
  inUse: string; // badge on a mitigation method the config actually uses
  rowUntitled: string; // repeatable row with no name yet
  removeRow: string;
  yamlShow: string;
  yamlHide: string;
  thrOff: string; // placeholder in an unset threshold cell
  helpToggle: string; // toolbar switch: show every field description inline
  helpOne: string; // per-field "what does this do?" button
  sectionErrs: string; // "{n}" placeholder — error count chip in a section header
  importer: {
    btn: string;
    hint: string;
    apply: string;
    cancel: string;
    bad: string; // "{err}" placeholder
    lost: string;
    lostNote: string;
    ok: string;
  };
  share: { btn: string; copied: string };
  reset: { btn: string; confirm: string };
  runbook: {
    title: string;
    save: string;
    check: string;
    apply: string;
    dataplane: string;
    watch: string;
    live: string;
  };
  validation: WizardValidation;
};

